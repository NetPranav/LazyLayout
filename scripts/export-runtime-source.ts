/**
 * The expression engine's evaluator as plain JavaScript, for the exported page (Design track D5, FX-EXP-01: the export runs
 * readable source, and imports no LazyLayout package). It is made from the core's own `expressions/noise.ts` and
 * `expressions/evaluate.ts`, so the editor and the export run the same code; `npm run build:export-runtime` writes it to
 * `src/core/export/runtime/generated/expressionRuntime.ts`, and a unit test fails if that file is out of date.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import ts from "typescript";

const SOURCES = ["src/core/expressions/noise.ts", "src/core/expressions/evaluate.ts"];

/** TypeScript to plain JS with the module syntax taken off: one scope of functions, ready to sit inside an IIFE. */
function plain(file: string, root: string): string {
  const out = ts.transpileModule(readFileSync(join(root, file), "utf8"), { compilerOptions: { target: ts.ScriptTarget.ES2019, module: ts.ModuleKind.ESNext, removeComments: false } }).outputText;
  return out
    .split("\n")
    .filter((line) => !/^import\s/.test(line))
    .map((line) => line.replace(/^export\s+(?=function|const|class|let|var)/, ""))
    .join("\n")
    .trim();
}

export function buildExpressionRuntimeSource(root = process.cwd()): string {
  const body = SOURCES.map((f) => `/* from ${f} */\n${plain(f, root)}`).join("\n\n");
  return `var EXPR = (function () {\n${body}\nreturn { evaluateExpression: evaluateExpression, noise1: noise1 };\n})();`;
}

export function generatedModuleText(root = process.cwd()): string {
  return `/* GENERATED by scripts/export-runtime-source.ts (npm run build:export-runtime). Do not edit: change src/core/expressions and rebuild. */\nexport const EXPRESSION_RUNTIME_SOURCE = ${JSON.stringify(buildExpressionRuntimeSource(root))};\n`;
}
